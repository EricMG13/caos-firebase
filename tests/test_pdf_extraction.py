# Where the fixture draws them: 12pt text at x=72, sixteen points apart.
LEFT_MARGIN = 72.0
LINE_GAP = 16.0


def raw_pdf(
    content: bytes,
    *,
    trailer: bytes = b"",
    page: bytes = b"",
    pages: bytes = b"",
    media: bytes = b"0 0 612 792",
) -> bytes:
    """A one-page PDF whose content stream is exactly `content`.

    Written out rather than generated by a library, so the fixture has no
    dependency of its own and its contents are legible in the diff. `trailer`
    is spliced into the trailer dictionary -- an `/Encrypt` entry is how a
    fixture becomes an encrypted document; `page` is spliced into the page
    dictionary, which is how one gains a `/Rotate` or a `/CropBox`, and `pages`
    into its parent `Pages` node, which is how a page inherits one. Every other
    builder in this file is a content-stream shorthand over this one, so a
    reviewer sees the same PDF object machinery once.
    """
    return _assemble(_objects(content, page=page, pages=pages, media=media), trailer)


def encoded_pdf(content: bytes, differences: bytes) -> bytes:
    """`raw_pdf`'s page with its font re-encoded: `differences` is a
    `/Differences` array's body, so `120 /uni2ADC` draws every `x` as U+2ADC.
    How a fixture reaches characters no standard encoding carries. Not a
    standard-14 name, so pdfminer reads the glyph widths the font declares
    (half an em each) instead of Helvetica's, which have no such glyph."""
    widths = b" ".join([b"500"] * 95)
    objects = _objects(content)
    objects[-1] = (
        b"<< /Type /Font /Subtype /Type1 /BaseFont /CaosFixture /FirstChar 32"
        b" /LastChar 126 /Widths [" + widths + b"] /Encoding << /Type /Encoding"
        b" /Differences [" + differences + b"] >> >>"
    )
    return _assemble(objects)


def _objects(
    content: bytes,
    *,
    page: bytes = b"",
    pages: bytes = b"",
    media: bytes = b"0 0 612 792",
) -> list[bytes]:
    """The catalog, the page tree, the page, its content and its font."""
    return [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 " + pages + b" >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox ["
        + media
        + b"] "
        + page
        + b" /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
        b"<< /Length "
        + str(len(content)).encode()
        + b" >>\nstream\n"
        + content
        + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]


def _assemble(objects: list[bytes], trailer: bytes = b"") -> bytes:
    """`objects`, numbered from one, with their cross-reference table."""
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += str(number).encode() + b" 0 obj\n" + body + b"\nendobj\n"
    start_xref = len(out)
    out += b"xref\n0 " + str(len(objects) + 1).encode() + b"\n0000000000 65535 f \n"
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode()
    out += (
        b"trailer\n<< /Size "
        + str(len(objects) + 1).encode()
        + b" /Root 1 0 R "
        + trailer
        + b">>\nstartxref\n"
        + str(start_xref).encode()
        + b"\n%%EOF\n"
    )
    return bytes(out)


def minimal_pdf(lines: list[str], *, trailer: bytes = b"") -> bytes:
    """A one-page PDF drawing each line at a known position, one `Tj` each."""
    text = "BT\n/F1 12 Tf\n"
    y = 700
    for line in lines:
        text += f"1 0 0 1 {LEFT_MARGIN:.0f} {y} Tm\n({line}) Tj\n"
        y -= int(LINE_GAP)
    text += "ET\n"
    return raw_pdf(text.encode("ascii"), trailer=trailer)


def kerned_pdf(first: str, second: str, offset: int) -> bytes:
    """One line, one `TJ` array: `first` then `second`, with no drawn space
    glyph between them -- only the numeric `offset` (thousandths of a text
    space unit; negative widens the gap) pdfminer's own layout analysis reads
    to decide whether a word break belongs there (§44.5)."""
    content = (
        f"BT\n/F1 12 Tf\n1 0 0 1 {LEFT_MARGIN:.0f} 700 Tm\n"
        f"[({first}){offset}({second})]TJ\nET\n"
    ).encode("ascii")
    return raw_pdf(content)


def tracked_pdf(word: str, tc: float) -> bytes:
    """One word, drawn glyph by glyph with `Tc` character-tracking spacing
    applied between every pair -- no `TJ` offsets, no drawn spaces."""
    content = (
        f"BT\n/F1 12 Tf\n1 0 0 1 {LEFT_MARGIN:.0f} 700 Tm\n{tc} Tc\n({word}) Tj\nET\n"
    ).encode("ascii")
    return raw_pdf(content)


COLUMN_X = 400.0


def two_column_pdf(left: list[str], right: list[str]) -> bytes:
    """Two independent text columns positioned with `Tm`, far enough apart
    (`LEFT_MARGIN` vs `COLUMN_X`) that pdfminer's layout analysis places them
    in separate regions -- two `LTTextBox`es, never one phrase across the
    gutter."""
    text = "BT\n/F1 12 Tf\n"
    y = 700
    for line in left:
        text += f"1 0 0 1 {LEFT_MARGIN:.0f} {y} Tm\n({line}) Tj\n"
        y -= int(LINE_GAP)
    y = 700
    for line in right:
        text += f"1 0 0 1 {COLUMN_X:.0f} {y} Tm\n({line}) Tj\n"
        y -= int(LINE_GAP)
    text += "ET\n"
    return raw_pdf(text.encode("ascii"))


