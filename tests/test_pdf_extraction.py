# A text matrix per quarter turn that draws left-to-right *as displayed*: the
# inverse of the page's `/Rotate`, which is how a landscape page is authored.
UPRIGHT = {0: "1 0 0 1", 90: "0 1 -1 0", 180: "-1 0 0 -1", 270: "0 -1 1 0"}


def placed_pdf(
    words: list[tuple[str, int, int]],
    *,
    rotate: int = 0,
    crop: str = "",
    media: str = "0 0 612 792",
    declared: tuple[Literal["page", "pages"], str] | None = None,
) -> bytes:
    """Each `(word, x, y)` drawn at user-space `(x, y)`, upright once the
    page's `rotate` is applied, on a `media` MediaBox with an optional
    `/CropBox [crop]`. `declared` is where the `/Rotate` entry is written and
    its value -- the page itself or its parent `Pages` node; by default the
    page, with `rotate`."""
    text = "BT\n/F1 12 Tf\n"
    for word, x, y in words:
        text += f"{UPRIGHT[rotate]} {x} {y} Tm\n({word}) Tj\n"
    (holder, value) = declared or ("page", str(rotate))
    entry = f"/Rotate {value}"
    page = (entry if holder == "page" else "") + (f" /CropBox [{crop}]" if crop else "")
    return raw_pdf(
        (text + "ET\n").encode("ascii"),
        page=page.encode("ascii"),
        pages=(entry if holder == "pages" else "").encode("ascii"),
        media=media.encode("ascii"),
    )


